// Writes each app's .env.local so it points at a Supabase instance.
//
//   node scripts/env.ts --local   use the local Supabase started by `pnpm db:start`
//   node scripts/env.ts --dev     use the hosted dev project from SUPABASE_DEV_* env vars
//
// Existing keys in an app's .env.local that this script does not manage (for
// example EXPO_PUBLIC_POSTHOG_API_KEY) are kept.

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type Supabase = { url: string; anonKey: string; serviceKey: string };

const root = join(import.meta.dirname, '..');

const readLocal = (): Supabase => {
  let output: string;
  try {
    output = execFileSync('pnpm', ['exec', 'supabase', 'status', '-o', 'env'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
  } catch {
    throw new Error('Local Supabase is not running. Start it with `pnpm db:start` first.');
  }
  const status = parseEnv(output);
  return {
    url: status.API_URL,
    anonKey: status.ANON_KEY ?? status.PUBLISHABLE_KEY,
    serviceKey: status.SERVICE_ROLE_KEY ?? status.SECRET_KEY,
  };
};

const readDev = (): Supabase => {
  const missing = ['SUPABASE_DEV_URL', 'SUPABASE_DEV_ANON_KEY', 'SUPABASE_DEV_SERVICE_KEY'].filter(
    (name) => !process.env[name],
  );
  if (missing.length > 0) {
    throw new Error(`Missing ${missing.join(', ')}. Set them in your shell or cloud environment.`);
  }
  return {
    url: process.env.SUPABASE_DEV_URL as string,
    anonKey: process.env.SUPABASE_DEV_ANON_KEY as string,
    serviceKey: process.env.SUPABASE_DEV_SERVICE_KEY as string,
  };
};

const parseEnv = (text: string): Record<string, string> => {
  const values: Record<string, string> = {};
  for (const line of text.split('\n')) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (match) values[match[1]] = match[2].replace(/^"(.*)"$/, '$1');
  }
  return values;
};

const writeEnv = (app: string, values: Record<string, string>) => {
  const file = join(root, 'apps', app, '.env.local');
  const current = existsSync(file) ? parseEnv(readFileSync(file, 'utf8')) : {};
  const merged = { ...current, ...values };
  const body = Object.entries(merged)
    .map(([key, value]) => `${key}=${value}`)
    .join('\n');
  writeFileSync(
    file,
    `# Generated by scripts/env.ts. Safe to edit; re-running keeps unmanaged keys.\n${body}\n`,
  );
  console.log(`  wrote apps/${app}/.env.local`);
};

const mode = process.argv[2];
if (mode !== '--local' && mode !== '--dev') {
  console.error('Usage: node scripts/env.ts --local | --dev');
  process.exit(1);
}

try {
  const supabase = mode === '--local' ? readLocal() : readDev();
  console.log(`Pointing apps at ${supabase.url}`);
  writeEnv('mobile', {
    EXPO_PUBLIC_SUPABASE_URL: supabase.url,
    EXPO_PUBLIC_SUPABASE_ANON_KEY: supabase.anonKey,
  });
  writeEnv('scraper', {
    SUPABASE_URL: supabase.url,
    SUPABASE_KEY: supabase.serviceKey,
    ENABLE_SUPABASE: 'true',
  });
} catch (error) {
  console.error((error as Error).message);
  process.exit(1);
}
