import { execFileSync } from 'node:child_process';
import { readdirSync } from 'node:fs';
import { parseArgs } from 'node:util';

const START = '<!-- ios-screenshots:start -->';
const END = '<!-- ios-screenshots:end -->';

export type Shot = { name: string; light?: string; dark?: string };

export function groupShots(files: string[]): Shot[] {
  const byName = new Map<string, Shot>();
  for (const file of files.sort()) {
    const match = /^(.+)-(light|dark)\.png$/.exec(file);
    if (!match) continue;
    const [, name, theme] = match;
    const shot = byName.get(name) ?? { name };
    if (theme === 'light') shot.light = file;
    else shot.dark = file;
    byName.set(name, shot);
  }
  return [...byName.values()];
}

export function screenshotSection(shots: Shot[], baseUrl: string, caption: string): string {
  const cell = (file?: string) => (file ? `<img src="${baseUrl}/${file}" width="220">` : '');
  const rows = shots.map((s) => `| ${s.name} | ${cell(s.light)} | ${cell(s.dark)} |`);
  return [
    START,
    '## Screenshots',
    '',
    caption,
    '',
    '| Screen | Light | Dark |',
    '|---|---|---|',
    ...rows,
    END,
  ].join('\n');
}

export function withSection(body: string, section: string): string {
  const start = body.indexOf(START);
  const end = body.indexOf(END);
  if (start !== -1 && end > start) {
    return `${body.slice(0, start)}${section}${body.slice(end + END.length)}`;
  }
  const marker = body.search(/\n---\n_Generated by|\n🤖 Generated with/);
  if (marker !== -1) {
    return `${body.slice(0, marker).trimEnd()}\n\n${section}\n${body.slice(marker)}`;
  }
  return `${body.trimEnd()}\n\n${section}\n`;
}

function gh(args: string[], input?: string): string {
  return execFileSync('gh', args, { encoding: 'utf8', input, stdio: ['pipe', 'pipe', 'inherit'] });
}

function main() {
  const { values } = parseArgs({
    options: {
      repo: { type: 'string', default: 'EthanL06/UT-Dining' },
      pr: { type: 'string' },
      sha: { type: 'string' },
      dir: { type: 'string' },
      caption: { type: 'string', default: 'iOS screenshots.' },
    },
  });
  const { repo, pr, sha, dir, caption } = values;
  if (!(pr && sha && dir)) {
    throw new Error('usage: pr-screenshots-body.ts --pr <n> --sha <assets commit> --dir <pngs>');
  }
  const shots = groupShots(readdirSync(dir));
  if (shots.length === 0) throw new Error(`no <name>-<light|dark>.png files in ${dir}`);
  const section = screenshotSection(
    shots,
    `https://raw.githubusercontent.com/${repo}/${sha}`,
    caption,
  );
  const current = JSON.parse(gh(['api', `repos/${repo}/pulls/${pr}`])).body ?? '';
  const body = withSection(current, section);
  gh(['api', '-X', 'PATCH', `repos/${repo}/pulls/${pr}`, '--input', '-'], JSON.stringify({ body }));
  process.stdout.write(`Embedded ${shots.length} screen(s) in the body of PR #${pr}\n`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
